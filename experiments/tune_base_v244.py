def _estimate_attack_damage(card_id, attack_id, option_idx=None):
    """估算攻击伤害。三级 fallback（[v22-bugfix] 移除 option_idx→moves 错位索引）"""
    # 1. 全局 attackId 精确映射（replay 反查）
    if attack_id is not None and attack_id in _ATTACK_ID_DMG:
        return _ATTACK_ID_DMG[attack_id]
    # 2. 卡内招式表（attackId 恰为招式索引时使用）
    data = _CARD_DB.get(card_id)
    if data:
        moves = data.get("moves", [])
        if attack_id is not None and isinstance(attack_id, int) and 0 <= attack_id < len(moves):
            return moves[attack_id][0]
        if moves:
            return max((m[0] for m in moves), default=0)
        # [v22.6] 生成条目无 moves 时回退 power (最大招式伤害)
        power = data.get("power", 0)
        if power > 0:
            return power
    return 0


def _calculate_ko_damage(base_dmg, my_cid, opp_pokemon):
    """[B1] 计算考虑类型弱点后的实际伤害

    PTCG 弱点规则: 攻击方属性 == 防御方弱点 → 伤害 ×2
    我方卡组属性:
      756: 無 (Colorless)
      344/345: 草 (Grass)
      117: 闘 (Fighting)
    """
    if base_dmg <= 0:
        return 0

    # [BUG-8 fix] 676ソルロック コズミックビーム 无视弱点/抵抗 (效果无视),
    # 不参与弱点×2, 否则会高估其斩杀线
    if my_cid == 676:
        return base_dmg

    my_data = _CARD_DB.get(my_cid, {})
    my_type = _norm_type_name(my_data.get("type", None))

    opp_weakness = _get_pokemon_weakness(opp_pokemon)

    # 弱点匹配 → 伤害 ×2 ([v22.6-fix3] 双方均归一化为规范日文属性)
    if my_type and opp_weakness and my_type == opp_weakness:
        return base_dmg * 2

    return base_dmg


def _sanitize(indices, options_len, max_count):
    """动作合法性铁律：长度==maxCount、下标合法、无重复

    [C1] 修复: 原 while 循环在 max_count > options_len 时可能无限循环。
         新增 max_iter 上限保护，超出后直接返回已收集的结果。
    """
    # [C4] max_count 类型守卫
    # [P1] 修复: max_count<=0 时返回 [0] 而非空列表，确保引擎不因空动作崩溃
    if not isinstance(options_len, int) or options_len <= 0:
        return []
    if not isinstance(max_count, int) or max_count <= 0:
        return [0]
    # max_count 不能超过 options_len
    max_count = min(max_count, options_len)

    if not indices:
        indices = list(range(max_count))

    seen = set()
    clean = []
    for idx in indices:
        if isinstance(idx, int) and 0 <= idx < options_len and idx not in seen:
            clean.append(idx)
            seen.add(idx)

    # [C1] 安全填充：最多循环 options_len 次，防止无限循环
    if len(clean) < max_count:
        for i in range(options_len):
            if len(clean) >= max_count:
                break
            if i not in seen:
                clean.append(i)
                seen.add(i)

    return clean[:max_count]


