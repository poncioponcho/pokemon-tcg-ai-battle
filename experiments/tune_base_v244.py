def _resolve_card_id_from_option(opt, obs_current, my_idx):
    """从 option 解析真实 card_id（area+index 查表）

    真实引擎 option 结构（replay 确认）:
      Card 选项:   {"area": 2, "index": 1, "playerIndex": 0, "type": "Card"}
      Attach选项:  {"area": 2, "inPlayArea": 4, "inPlayIndex": 0, "index": 2, "type": "Attach"}
      Evolve选项:  {"area": 2, "inPlayArea": 4, "inPlayIndex": 0, "index": 6, "type": "Evolve"}
      Play选项:    {"index": 5, "type": "Play"}
    area 语义: 1=deck 2=hand 3=discard 4=active 5=bench
    """
    if not isinstance(opt, dict):
        return -1

    # 1. 直接 cardId/id 字段
    for key in ("cardId", "card_id", "id"):
        val = opt.get(key)
        if isinstance(val, int) and val >= 0:
            return val

    area = opt.get("area", -1)
    index = opt.get("index", -1)
    player_index = opt.get("playerIndex", my_idx)
    if not isinstance(index, int) or index < 0:
        return -1

    # Play/Attach/Evolve 选项无 area 字段（replay 确认），index 指向手牌
    ot = _get_option_type(opt)
    if ot in ("Play", "Attach", "Evolve") and area != 2:
        area = 2

    try:
        players = obs_current.get("players", [])
        if not players:
            return -1
        if not isinstance(player_index, int) or not (0 <= player_index < len(players)):
            player_index = my_idx
        player = players[player_index]
        if not isinstance(player, dict):
            return -1

        if area == 2:  # hand
            hand = player.get("hand", [])
            if isinstance(hand, list) and index < len(hand) and isinstance(hand[index], dict):
                return hand[index].get("id", -1)
        elif area == 5:  # bench
            bench = player.get("bench", [])
            if isinstance(bench, list) and index < len(bench) and isinstance(bench[index], dict):
                return bench[index].get("id", -1)
        elif area == 4:  # active
            active = player.get("active", [])
            if isinstance(active, list) and active and isinstance(active[0], dict):
                # [审计-M3] index>0 表示选择 active 上的附属卡(能量/工具),
                # 必须按 index 在 energies/energyCards 中查找, 避免把能量误判为宝可梦
                if index > 0:
                    for key in ("energies", "energyCards"):
                        lst = active[0].get(key, [])
                        if isinstance(lst, list) and index < len(lst) and isinstance(lst[index], dict):
                            return lst[index].get("id", -1)
                    return -1
                return active[0].get("id", -1)
        elif area == 1:  # deck
            deck = player.get("deck", [])
            if isinstance(deck, list) and index < len(deck) and isinstance(deck[index], dict):
                return deck[index].get("id", -1)
        elif area == 3:  # discard
            discard = player.get("discard", [])
            if isinstance(discard, list) and index < len(discard) and isinstance(discard[index], dict):
                return discard[index].get("id", -1)
    except Exception:
        pass
    return -1


def _get_pokemon_hp(pokemon):
    """从 pokemon dict 安全读取 HP

    [P7] 修复: 原代码使用 `or` 链，当 hp=0（昏厥）时 0 为 falsy，
         会错误地 fallback 到 remainingHp。改为显式 None 检查。
    """
    if not isinstance(pokemon, dict):
        return 0
    hp = pokemon.get("hp")
    if hp is not None:
        return hp
    return pokemon.get("remainingHp") or 0


def _get_pokemon_max_hp(pokemon):
    """从 pokemon dict 安全读取 maxHp

    [P7] 修复: 原代码 `maxHp or hp or 0`，当 maxHp 缺失时 fallback 到 hp（当前 HP），
         导致 HP 比例计算错误（如 50/100 → 50/50=100%）。
         修复: 优先 maxHp → 卡数据库 hp → hp 字段。
    """
    if not isinstance(pokemon, dict):
        return 0
    max_hp = pokemon.get("maxHp")
    if max_hp is not None and max_hp > 0:
        return max_hp
    # Fallback: 从卡数据库读取
    cid = _get_pokemon_card_id(pokemon)
    if cid >= 0:
        card_hp = _CARD_DB.get(cid, {}).get("hp", 0)
        if card_hp > 0:
            return card_hp
    return pokemon.get("hp") or 0


def _get_pokemon_energy_count(pokemon):
    """从 pokemon dict 安全读取能量数量"""
    if not isinstance(pokemon, dict):
        return 0
    energies = pokemon.get("energies")
    if isinstance(energies, list):
        return len(energies)
    if isinstance(energies, dict):
        return sum(energies.values())
    return 0


def _get_pokemon_card_id(pokemon):
    """从 pokemon dict 安全读取 card_id"""
    if not isinstance(pokemon, dict):
        return -1
    for key in ("cardId", "card_id", "id"):
        val = pokemon.get(key)
        if isinstance(val, int) and val >= 0:
            return val
    return -1


def _get_pokemon_weakness(pokemon):
    """[B1] 从 pokemon dict 安全读取弱点类型

    真实引擎中 weakness 字段可能为:
      - 字符串: "闘" (直接弱点类型)
      - 列表: [{"type": "闘", "value": 2}] (结构化弱点)
      - dict: {"type": "闘", "value": 2}
      - None: 无弱点
    引擎观测的 pokemon dict 从不暴露 weakness 字段，因此最后回退到
    _CARD_DB 按卡牌 id 查弱点（卡库覆盖全部宝可梦）。
    """
    if not isinstance(pokemon, dict):
        return None
    weak = pokemon.get("weakness") or pokemon.get("weaknesses")
    if isinstance(weak, int):
        return _norm_type_name(weak) or None
    if isinstance(weak, str):
        return _norm_type_name(weak) or None
    if isinstance(weak, dict):
        return _norm_type_name(weak.get("type", None)) or None
    if isinstance(weak, list) and weak:
        first = weak[0]
        if isinstance(first, dict):
            return _norm_type_name(first.get("type", None)) or None
        if isinstance(first, str):
            return _norm_type_name(first) or None
    # [bugfix] 引擎观测不携带 weakness，回退卡库按 id 查
    cid = _get_pokemon_card_id(pokemon)
    if cid >= 0:
        return _norm_type_name(_CARD_DB.get(cid, {}).get("weakness", None)) or None
    return None


