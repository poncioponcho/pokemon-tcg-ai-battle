def _norm_type(value):
    """规范化 option.type（仅查 _OPT_NUM_TO_STR）

    [v16 修复] select.type 和 option.type 的数字映射存在冲突
    （如 7='Evolve' vs 'Play'，8='Count' vs 'Attach'，9='YesNo' vs 'Evolve'），
    必须使用独立函数避免交叉污染。
    本函数仅用于 option.type 规范化。
    """
    if isinstance(value, str):
        return value
    if isinstance(value, int) and value in _OPT_NUM_TO_STR:
        return _OPT_NUM_TO_STR[value]
    return value


def _norm_select_type(value):
    """规范化 select.type（仅查 _SELECT_NUM_TO_STR）

    [v16 修复] 与 _norm_type 分离，避免 option.type 映射覆盖 select.type。
    冲突示例: select.type=1 应为 'Card'，但 _norm_type 返回 'Yes'（OptionType 1='Yes'）。
    """
    if isinstance(value, str):
        return value
    if isinstance(value, int) and value in _SELECT_NUM_TO_STR:
        return _SELECT_NUM_TO_STR[value]
    return value


