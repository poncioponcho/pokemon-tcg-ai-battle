def agent(obs, config=None):
    """Kaggle Agent 入口函数。

    参数：
        obs   : dict — Kaggle cabt 引擎传入的 observation
        config: any  — Kaggle Environments 配置（未使用）

    返回：
        list[int] — 选中的 option index 列表
    """
    global _error_count
    global _PENDING_SWITCH_TO_WALL

    # [v23-fix][BUG-3] obs=None 防御: 返回空列表, 防止 AttributeError 崩溃
    if obs is None:
        return []

    # [v24.4] 对局状态生命周期 (防死循环 _OSC; 覆盖所有入口, v22.6-fix4 教训)
    _maybe_reset_game_state(obs)

    # ---- Phase 0: 初始上牌阶段 ----
    if obs.get("select") is None:
        _PENDING_SWITCH_TO_WALL = False  # [v22.6-fix4] 新对局开始, 清除历史残留
        return DECK

    try:
        select = obs["select"]
        options = select.get("option", [])
        # [审计-H1] option 必须是 list, 否则按空处理 —— 防止 dict/None 等
        # 异常结构在主路径上产生非法下标动作
        if not isinstance(options, list):
            return []
        max_count = select.get("maxCount", 1)
        sel_type = _norm_select_type(select.get("type", None))
        context = _norm_context(select.get("context", None))
        obs_current = obs.get("current", {})
        my_idx = obs_current.get("yourIndex", 0)
        if not isinstance(my_idx, int) or my_idx not in (0, 1):
            my_idx = 0

        # [v22.6-fix4] 换墙意图只允许跨一次 Main→Card; 非 Card 决策直接清空
        if sel_type != _ST_CARD:
            _PENDING_SWITCH_TO_WALL = False

        # [C4] max_count 类型守卫
        if not isinstance(max_count, int) or max_count <= 0:
            max_count = 1

        n = len(options)
        if n == 0:
            return []

        # 全选优化：maxCount >= 选项数时直接全选
        if max_count >= n:
            return list(range(n))

        # [A4] 短路：只有一个选项时直接返回
        if n == 1:
            return [0]

        # [A2] 字典分发路由
        handler = _HANDLERS.get(sel_type)
        if handler:
            _rule_action = handler(options, max_count, context, obs_current, my_idx)
            # [v24.4] 防死循环: A→B→A 振荡干预 (仅 Main 决策; 取 End 破环)
            if sel_type == _ST_MAIN and _PARAMS['osc_break_enabled']:
                _rule_action = _osc_intervene(_rule_action, options, max_count)
            # [v24] NN Advisor: 规则为锚, NN 高置信分歧时纠偏; 任何异常内部消化
            _action = _nn_consult(obs, sel_type, options, max_count, _rule_action)
            # [v24.4] 记录 Main 决策历史 (Step 5 _GAME_STATE 复用)
            if sel_type == _ST_MAIN:
                _osc_record(_action, options, obs_current, my_idx)
            return _action

        if sel_type == _ST_NONE:
            return _sanitize(list(range(min(max_count, n))), n, max_count)

        # 未知 sel_type 兜底
        return _sanitize(list(range(max_count)), n, max_count)

    except Exception as e:
        # [C3] 异常追踪增强：记录错误类型
        # [P5] 添加 stderr 日志输出，避免异常静默吞没导致难以调试
        _error_count += 1
        _error_types[type(e).__name__] += 1
        try:
            sys.stderr.write(f"[PTCG Agent] Error #{_error_count}: {type(e).__name__}: {e}\n")
        except Exception:
            pass

        # [P0] 修复: 异常处理器使用确定性选择（前 N 个选项），不再使用 random.sample
        # [审计-H1] 兜底必须先验证 option 是非空 list, 否则返回 [] ——
        # 杜绝在 options 为 None/非法时返回不存在的下标 (违反动作铁律)
        try:
            select = obs.get("select", {})
            options = select.get("option", [])
            if not isinstance(options, list) or not options:
                return []
            n = len(options)
            max_count = select.get("maxCount", 1)
            if not isinstance(max_count, int) or max_count <= 0:
                max_count = 1
            return list(range(min(max_count, n)))
        except Exception:
            return []
