def agent(obs, config=None):
    """Kaggle Agent 入口函数。

    参数：
        obs   : dict — Kaggle cabt 引擎传入的 observation
        config: any  — Kaggle Environments 配置（未使用）

    返回：
        list[int] — 选中的 option index 列表
    """
    global _error_count
    global _PENDING_SWITCH_TO_WALL

    # ---- Phase 0: 初始上牌阶段 ----
    if obs.get("select") is None:
        _PENDING_SWITCH_TO_WALL = False  # [v22.6-fix4] 新对局开始, 清除历史残留
        return DECK

    try:
        select = obs["select"]
        options = select.get("option", [])
        max_count = select.get("maxCount", 1)
        sel_type = _norm_select_type(select.get("type", None))
        context = _norm_context(select.get("context", None))
        obs_current = obs.get("current", {})
        my_idx = obs_current.get("yourIndex", 0)
        if not isinstance(my_idx, int) or my_idx not in (0, 1):
            my_idx = 0

        # [v22.6-fix4] 换墙意图只允许跨一次 Main→Card; 非 Card 决策直接清空
        if sel_type != _ST_CARD:
            _PENDING_SWITCH_TO_WALL = False

        # [C4] max_count 类型守卫
        if not isinstance(max_count, int) or max_count <= 0:
            max_count = 1

        n = len(options)
        if n == 0:
            return []

        # 全选优化：maxCount >= 选项数时直接全选
        if max_count >= n:
            return list(range(n))

        # [A4] 短路：只有一个选项时直接返回
        if n == 1:
            return [0]

        # [A2] 字典分发路由
        handler = _HANDLERS.get(sel_type)
        if handler:
            return handler(options, max_count, context, obs_current, my_idx)

        if sel_type == _ST_NONE:
            return _sanitize(list(range(min(max_count, n))), n, max_count)

        # 未知 sel_type 兜底
        return _sanitize(list(range(max_count)), n, max_count)

    except Exception as e:
        # [C3] 异常追踪增强：记录错误类型
        # [P5] 添加 stderr 日志输出，避免异常静默吞没导致难以调试
        _error_count += 1
        _error_types[type(e).__name__] += 1
        try:
            import sys
            sys.stderr.write(f"[PTCG Agent] Error #{_error_count}: {type(e).__name__}: {e}\n")
        except Exception:
            pass

        # [P0] 修复: 异常处理器使用确定性选择（前 N 个选项），不再使用 random.sample
        try:
            select = obs.get("select", {})
            options = select.get("option", [])
            n = len(options)
            if n == 0:
                return []
            max_count = select.get("maxCount", 1)
            if not isinstance(max_count, int) or max_count <= 0:
                max_count = 1
            max_count = min(max_count, n)
            return list(range(max_count))
        except Exception:
            return [0]
