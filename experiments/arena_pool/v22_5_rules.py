def _handle_main(options, max_count, context, obs_current, my_idx):
    """MAIN(0)：主菜单 — Mega Wall Push 决策引擎
    多核墙推策略决策链:
      P1.  KO攻击 (含弱点×2) → ATTACK
      P2.  bench空 → PLAY宝可梦 (防输)
      P3.  进化345イワパレス → EVOLVE (墙成型关键)
      P4.  756 active有3能量 → ATTACK (200+伤害推队)
      P5.  冲刺模式(奖赏卡≤2)有攻击 → ATTACK
      P6.  关键训练家卡时机 (ポフィン/リーリエ/トウコ)
      P7.  进化任意宝可梦
      P8.  active能量不足 → ATTACH to active
      P9.  ATTACK (伤害≥60)
      P10. PLAY训练家卡
      P11. PLAY宝可梦到bench
      P12. ATTACH to bench (优先756メガガルーラex)
      P13. ABILITY (756のおつかいダッシュ等)
      P14. ATTACK (弱攻击兜底)
      P15. ATTACH to active (积攒)
      P16. RETREAT/SWITCH (墙↔打手切换)
      P17. END / DISCARD
      P18. 兜底
    """
    global _PENDING_SWITCH_TO_WALL  # [v22.4] 换墙意图传递

    n = len(options)
    if n == 0:
        return []
    if n == 1:
        return _sanitize([0], n, max_count)

    # [v22.6-fix4] 新 Main 决策作废任何残留的换墙意图 (意图只存活一次 Main→Card)
    _PENDING_SWITCH_TO_WALL = False

    # === 状态提取 ===
    my_active = _get_my_active(obs_current, my_idx)
    opp_active = _get_opp_active(obs_current, my_idx)
    my_hp = _get_pokemon_hp(my_active)
    my_max_hp = _get_pokemon_max_hp(my_active)
    opp_hp = _get_pokemon_hp(opp_active)
    my_cid = _get_pokemon_card_id(my_active) if my_active else -1
    my_energy = _get_pokemon_energy_count(my_active)
    bench = _get_my_bench(obs_current, my_idx)
    hand = _get_my_hand(obs_current, my_idx)
    bench_count = len(bench)

    my_prize = _get_my_prize_count(obs_current, my_idx)
    sprint_mode = my_prize <= _PRIZE_SPRINT_THRESHOLD

    my_card_data = _CARD_DB.get(my_cid, {})
    my_needed_energy = my_card_data.get("needed_energy", 0)
    my_can_attack = my_card_data.get("can_attack", True)

    # === 检查对方是否为ex宝可梦 (墙策略判断) ===
    # [v22.6-fix2] 优先用卡库 rule 判断; 卡库未覆盖时才用 hp>=200 启发式
    opp_cid = _get_pokemon_card_id(opp_active) if opp_active else -1
    _opp_db = _CARD_DB.get(opp_cid, {})
    opp_is_ex = _opp_db.get("rule") in ("ex", "mega_ex") or (
        not _opp_db and opp_hp >= 200)

    # === [v22.4] 对方 345 イワパレス 墙识别 (免疫 ex 伤害) ===
    # 我方 ex 打手 (756/117) 对它的攻击无效, 必须换非ex的345攻击或用ボスの指令
    opp_is_wall = (opp_cid == 345)
    # 我方 ex 打手 ID 集 (攻击 345 墙无效)
    my_ex_ids = (756, 117)
    my_is_ex_attacker = my_cid in my_ex_ids

    # === 检查我方 345 墙是否可切换上场 ===
    bench_has_345 = any(_get_pokemon_card_id(bp) == 345 for bp in bench if isinstance(bp, dict))

    # === 检查bench是否有756 (推队准备) ===
    bench_has_756 = any(_get_pokemon_card_id(bp) == 756 for bp in bench if isinstance(bp, dict))
    bench_756_energy = 0
    for bp in bench:
        if isinstance(bp, dict) and _get_pokemon_card_id(bp) == 756:
            # [v22-bugfix] 多只756时取最大能量, 避免只查第一只漏判
            bench_756_energy = max(bench_756_energy, _get_pokemon_energy_count(bp))

    # [数据驱动] 756延迟推队: 满能但对方满血(>200)且345在bench → 换345磨血后再推
    # win方756攻击时对方HP≈140(残血收割), loss方≈310(满血打不死被反杀)
    delay_756_push = (my_cid == 756 and my_energy >= my_needed_energy
                      and opp_hp > 200 and bench_has_345)

    # === 选项分类 (单次遍历) ===
    opt_buckets = defaultdict(list)
    play_trainer_idx = []
    play_pokemon_idx = []

    for i, opt in enumerate(options):
        ot = _get_option_type(opt)
        if ot == _OT_ATTACK:
            opt_buckets["attack"].append(i)
        elif ot == _OT_ABILITY:
            opt_buckets["ability"].append(i)
        elif ot == _OT_EVOLVE:
            opt_buckets["evolve"].append(i)
        elif ot == _OT_ATTACH:
            in_play_area = opt.get("inPlayArea", -1) if isinstance(opt, dict) else -1
            if in_play_area == 4:
                opt_buckets["attach_active"].append(i)
            elif in_play_area == 5:
                opt_buckets["attach_bench"].append(i)
            else:
                opt_buckets["attach_other"].append(i)
        elif ot == _OT_PLAY:
            opt_buckets["play"].append(i)
            cid = _resolve_card_id_from_option(opt, obs_current, my_idx)
            if cid in _TRAINER_IDS:
                play_trainer_idx.append(i)
            elif not _is_energy_card(cid):
                # [v22-bugfix] 能量卡不会通过 Play 打出, 排除避免误判为宝可梦
                play_pokemon_idx.append(i)
        elif ot == _OT_RETREAT:
            opt_buckets["retreat"].append(i)
        elif ot == _OT_DISCARD:
            opt_buckets["discard"].append(i)
        elif ot == _OT_END:
            opt_buckets["end"].append(i)

    attack_idx = opt_buckets.get("attack", [])
    ability_idx = opt_buckets.get("ability", [])
    evolve_idx = opt_buckets.get("evolve", [])
    attach_active_idx = opt_buckets.get("attach_active", [])
    attach_bench_idx = opt_buckets.get("attach_bench", [])
    attach_other_idx = opt_buckets.get("attach_other", [])
    retreat_idx = opt_buckets.get("retreat", [])
    discard_idx = opt_buckets.get("discard", [])
    end_idx = opt_buckets.get("end", [])

    # === 计算最佳可用攻击伤害 ===
    best_attack_idx = -1
    best_attack_dmg = -1
    for k, idx in enumerate(attack_idx):
        attack_id = options[idx].get("attackId") if isinstance(options[idx], dict) else None
        dmg = _estimate_attack_damage(my_cid, attack_id)
        if dmg > best_attack_dmg:
            best_attack_dmg = dmg
            best_attack_idx = idx

    ko_dmg = _calculate_ko_damage(best_attack_dmg, my_cid, opp_active) if opp_active else best_attack_dmg

    # === Mega Wall Push 统一优先级链 ===

    # [v22.4] ex 打手面对 345 墙时攻击无效, 禁止所有攻击路径
    no_attack_wall = (opp_is_wall and my_is_ex_attacker)

    # P1. KO攻击 (能赢就赢)
    if attack_idx and opp_hp > 0 and ko_dmg >= opp_hp and not no_attack_wall:
        return _sanitize([best_attack_idx], n, max_count)

    # P2. bench空必铺场 (active被KO后无替补=直接输)
    if play_pokemon_idx and bench_count == 0:
        return _sanitize([_find_best_play(play_pokemon_idx, hand, options)], n, max_count)

    # P3. 进化345イワパレス → EVOLVE (墙成型关键)
    if evolve_idx:
        best_evolve = _find_best_evolve(evolve_idx, options, obs_current, my_idx)
        if isinstance(best_evolve, int) and best_evolve < n:
            evolve_cid = _resolve_card_id_from_option(
                options[best_evolve], obs_current, my_idx)
            if evolve_cid == 345:
                return _sanitize([best_evolve], n, max_count)

    # P3.5 [v22.5] 换墙优先: ex打手面对(345墙 或 ex对手打不死) → 换345
    # 数据支撑 (subm_rec12 s137): 756面对345墙时 ABILITY(P13) 抢占换墙 → 一直打不穿
    # 用户需求: 对方ex上场时切上345 (345免疫ex伤害); 打不死对手时换墙防守
    if retreat_idx and bench and bench_has_345:
        # 345墙: 攻击必然无效(免疫ex伤害), 无条件换345破墙
        if my_is_ex_attacker and opp_is_wall:
            _PENDING_SWITCH_TO_WALL = True
            return _sanitize([retreat_idx[0]], n, max_count)
        # ex对手: 打不死才换墙防守 (能KO则保留攻击机会)
        if my_is_ex_attacker and opp_is_ex and not (ko_dmg >= opp_hp):
            _PENDING_SWITCH_TO_WALL = True
            return _sanitize([retreat_idx[0]], n, max_count)

    # P3.6 [v22.5] 换下345: 对方非ex非墙 + bench有756满能 → 切756推队
    # 用户需求: 对方ex没上场时切下345 (345做墙失去意义, 756打200更强)
    # 对方345墙时保持345对打(120有效), 不切756(ex被墙免疫)
    if (retreat_idx and bench and my_cid == 345
            and not opp_is_ex and not opp_is_wall
            and bench_has_756 and bench_756_energy >= _MEGA_NEEDED):
        return _sanitize([retreat_idx[0]], n, max_count)

    # P4. 756 active有3能量 → ATTACK (200+伤害推队)
    # [数据驱动] 推队时机: win方756攻击时对方HP≈140(残血收割KO), loss方≈310(满血打不死被反杀)
    # 对方满血(>200)且345在bench可磨血 → 延迟756出手, 交由P16换345消耗(120×2轮)
    if attack_idx and my_cid == 756 and my_energy >= my_needed_energy and not delay_756_push and not no_attack_wall:
        return _sanitize([best_attack_idx], n, max_count)

    # P5. 冲刺模式有攻击 → ATTACK
    if sprint_mode and attack_idx and best_attack_dmg > 0:
        return _sanitize([best_attack_idx], n, max_count)

    # P6. 关键训练家卡时机 (ポフィン/リーリエ/トウコ)
    if play_trainer_idx:
        best_trainer = _find_best_trainer_play(
            play_trainer_idx, hand, options, obs_current, my_idx)
        if best_trainer >= 0:
            best_trainer_opt = options[best_trainer] if best_trainer < n else {}
            best_trainer_hand_idx = best_trainer_opt.get("index", -1) if isinstance(best_trainer_opt, dict) else -1
            if 0 <= best_trainer_hand_idx < len(hand):
                best_trainer_cid = hand[best_trainer_hand_idx].get("id", -1) if isinstance(hand[best_trainer_hand_idx], dict) else -1
                # [v22.4-fix] リーリエの決心 手牌>=6 无收益, 不强制打出
                lillie_waste = best_trainer_cid == _TRAINER_LILLIE and len(hand) >= 6
                if best_trainer_cid in (_TRAINER_POFIN, _TRAINER_LILLIE, _TRAINER_TOUKO, _TRAINER_SIANO) and not lillie_waste:
                    return _sanitize([best_trainer], n, max_count)

    # P7. 进化任意宝可梦 (进化链推进)
    if evolve_idx:
        best_evolve = _find_best_evolve(evolve_idx, options, obs_current, my_idx)
        return _sanitize([best_evolve], n, max_count)

    # P8. active能量不足 → ATTACH to active
    # 特殊: 345イワパレス作为墙时也需能量(用于グレートシザー120伤害)
    if attach_active_idx and my_can_attack and my_energy < my_needed_energy:
        return _sanitize([attach_active_idx[0]], n, max_count)

    # P9. ATTACK (伤害≥60, 不浪费回合在弱攻击上)
    # [数据驱动] 756满能+对方满血(>200)+345在场 → 延迟出手, 交由P16换345磨血
    if attack_idx and best_attack_dmg >= 60 and not delay_756_push and not no_attack_wall:
        return _sanitize([best_attack_idx], n, max_count)

    # P10. PLAY训练家卡
    if play_trainer_idx:
        # [v22.4] 手牌>=6 时リーリエの決心(1227)无收益, 从候选剔除
        play_trainer_filtered = []
        for i in play_trainer_idx:
            opt = options[i] if i < len(options) else {}
            hand_idx = opt.get("index", -1) if isinstance(opt, dict) else -1
            if 0 <= hand_idx < len(hand):
                cid = hand[hand_idx].get("id", -1) if isinstance(hand[hand_idx], dict) else -1
                if cid == _TRAINER_LILLIE and len(hand) >= 6:
                    continue
            play_trainer_filtered.append(i)
        if play_trainer_filtered:
            best_play = _find_best_play(play_trainer_filtered, hand, options)
            return _sanitize([best_play], n, max_count)

    # P11. PLAY宝可梦到bench (扩展场面)
    if play_pokemon_idx:
        best_play = _find_best_play(play_pokemon_idx, hand, options)
        return _sanitize([best_play], n, max_count)

    # P12. ATTACH to bench (优先756メガガルーラex, 为推队做准备)
    if attach_bench_idx:
        # 优先给bench上的756贴能
        best_bench_attach = _find_best_bench_attach_mega(attach_bench_idx, bench, options)
        return _sanitize([best_bench_attach], n, max_count)

    # P13. ABILITY (756のおつかいダッシュ等)
    if ability_idx:
        return _sanitize([ability_idx[0]], n, max_count)

    # P14. ATTACK (弱攻击也优于空过; 延迟推队时交给P16切换)
    if attack_idx and not delay_756_push and not no_attack_wall:
        return _sanitize([best_attack_idx], n, max_count)

    # P15. ATTACH to active (积攒能量备用)
    if attach_active_idx:
        return _sanitize([attach_active_idx[0]], n, max_count)
    if attach_other_idx:
        return _sanitize([attach_other_idx[0]], n, max_count)

    # P16. RETREAT/SWITCH (墙↔打手切换)
    # 345作为墙被非ex打手克制时, 切换到756推队
    # 756能量不足时, 切换到345做墙
    # [数据驱动] 756满能但对方满血(>200)且345在场 → 换345磨血(120×2轮), 避免756打不死被反杀
    if retreat_idx and bench:
        # [v22.4] ex打手(756/117)面对345墙: 攻击无效, 换我方345上场破墙
        # 345 グレートシザー 120 可磨死 150HP 墙 (非ex不受免疫限制)
        # [v22.5] 已被 P3.5 提前覆盖, 保留兜底
        if my_is_ex_attacker and opp_is_wall and bench_has_345:
            _PENDING_SWITCH_TO_WALL = True
            return _sanitize([retreat_idx[0]], n, max_count)
        # 345 active + 对方非ex非墙 + bench有756满能 → 切换推队
        # [v22.5] 对方345墙时保持345对打(120有效), 切756反而无效(ex被墙免疫)
        if my_cid == 345 and not opp_is_ex and not opp_is_wall \
                and bench_has_756 and bench_756_energy >= _MEGA_NEEDED:
            return _sanitize([retreat_idx[0]], n, max_count)
        # 756 active + (能量不足 或 对方满血需345磨血) + bench有345 → 切换做墙
        if my_cid == 756 and bench_has_345:
            need_wall = (my_energy < my_needed_energy and opp_is_ex) or \
                        (my_energy >= my_needed_energy and opp_hp > 200)
            if need_wall:
                _PENDING_SWITCH_TO_WALL = True
                return _sanitize([retreat_idx[0]], n, max_count)
        # HP低于30% + bench有打手 → 撤退
        hp_ratio = my_hp / my_max_hp if my_max_hp > 0 else 0
        if hp_ratio < 0.3:
            bench_has_attacker = any(
                _CARD_DB.get(_get_pokemon_card_id(bp), {}).get("can_attack", False)
                for bp in bench if bp and isinstance(bp, dict)
            )
            if bench_has_attacker:
                return _sanitize([retreat_idx[0]], n, max_count)

    # P17. END > DISCARD
    if end_idx:
        return _sanitize([end_idx[0]], n, max_count)
    if discard_idx:
        return _sanitize([discard_idx[0]], n, max_count)

    # P18. 铁律兜底
    return _sanitize([0], n, max_count)


def _handle_card(options, max_count, context, obs_current, my_idx):
    """CARD(1)：选卡 — 按场景特化

    v16 修复: context 规范化（数字→字符串），使场景分支正确触发。
    v15 新增 [B4]: Switch/ToActive 场景下，若选项指向对方 bench（ボスの指令），
                   选 HP 最低的对方 bench 宝可梦（便于击杀拿奖赏卡）。
                   若选项指向我方 bench（撤退后选谁上场），按 power+HP 排序。
    v22.4: 消费 _PENDING_SWITCH_TO_WALL 标志 — 撤退换墙时优先选 345 上场
    """
    global _PENDING_SWITCH_TO_WALL  # [v22.4] 换墙意图消费

    n = len(options)
    if n == 0:
        return []

    # [v22.6-fix4] 进入选卡即消费意图 (无论是否走 Switch/ToActive 分支),
    # 保证意图最多跨一次 Main→Card, 不残留到后续决策或下一局
    switch_to_wall_intent = _PENDING_SWITCH_TO_WALL
    _PENDING_SWITCH_TO_WALL = False

    # [B4] Switch/ToActive 场景：判断是 ボスの指令（对方）还是 撤退（我方）
    if context in (_SC_SWITCH, _SC_TO_ACTIVE):
        targets_opp = False
        for opt in options:
            if isinstance(opt, dict):
                pi = opt.get("playerIndex", my_idx)
                if isinstance(pi, int) and pi != my_idx:
                    targets_opp = True
                    break

        if targets_opp:
            # ボスの指令：选 HP 最低的对方 bench 宝可梦（便于击杀拿奖赏卡）
            scored = []
            for i, opt in enumerate(options):
                if isinstance(opt, dict):
                    opt_hp = opt.get("hp", None)
                    if opt_hp is not None:
                        scored.append((opt_hp, i))
                        continue
                    cid = _resolve_card_id_from_option(opt, obs_current, my_idx)
                    if cid >= 0:
                        card_hp = _CARD_DB.get(cid, {}).get("hp", 999)
                        scored.append((card_hp, i))
                        continue
                scored.append((999, i))  # 未知 HP，排最后

            scored.sort()  # HP 低的排前面
            return _sanitize([idx for _, idx in scored[:max_count]], n, max_count)
        # else: 撤退（我方换人），fall through 到 power+HP 排序

    # 通用逻辑：setup/switch/toActive/toBench/evolvesFrom 按 power+hp 排序
    if context in (_SC_SETUP_ACTIVE, _SC_SETUP_BENCH, _SC_SWITCH,
                   _SC_TO_ACTIVE, _SC_TO_BENCH, _SC_EVOLVES_FROM,
                   _SC_EVOLVES_TO, _SC_ATTACH_FROM):
        # [v22.4] 消费换墙意图: 撤退换墙时优先选 345 上场 (一次性)
        switch_to_wall = switch_to_wall_intent
        # [v22.5] 被动换人(active阵亡): 对方 ex/345墙 在场时也优先选345墙
        # subm_rec12 s95: 345被KO后 ToActive 选了756, 对方756(400HP)ex在场被打穿
        opp_act = _get_opp_active(obs_current, my_idx)
        opp_cid = _get_pokemon_card_id(opp_act) if opp_act else -1
        opp_hp = _get_pokemon_hp(opp_act)
        _opp_db = _CARD_DB.get(opp_cid, {})
        opp_is_ex_t = _opp_db.get("rule") in ("ex", "mega_ex") or (
            not _opp_db and opp_hp >= 200)
        opp_is_wall_t = (opp_cid == 345)
        prefer_wall = switch_to_wall or opp_is_ex_t or opp_is_wall_t
        scored = []
        for i, opt in enumerate(options):
            cid = _resolve_card_id_from_option(opt, obs_current, my_idx)
            card_data = _CARD_DB.get(cid, {}) if cid >= 0 else {}
            power = card_data.get("power", 0)
            hp = card_data.get("hp", 0)
            is_basic = "evolves_from" not in card_data
            basic_bonus = 500 if is_basic else 0
            evolves_to = card_data.get("evolves_to", None)
            evolve_bonus = 50 if evolves_to else 0
            # [v22.4/v22.5] 换墙意图或对方ex/墙在场: 345 加权确保优先
            wall_bonus = 1000 if (prefer_wall and cid == 345) else 0
            scored.append((power + basic_bonus + evolve_bonus + wall_bonus, hp, i))
        scored.sort(reverse=True)
        return _sanitize([idx for _, _, idx in scored[:max_count]], n, max_count)

    # [P4] ToHand 场景：从弃牌堆/场上回手 — 优先回收训练家卡和进化卡
    if context == _SC_TO_HAND:
        scored = []
        for i, opt in enumerate(options):
            cid = _resolve_card_id_from_option(opt, obs_current, my_idx)
            card_data = _CARD_DB.get(cid, {}) if cid >= 0 else {}
            if cid in _TRAINER_IDS:
                priority = 200 + _TRAINER_PRIORITY.get(cid, 0)
            elif "evolves_from" in card_data:
                priority = 150
            elif not card_data.get("is_energy"):
                priority = 100
            else:
                priority = 30
            scored.append((priority, i))
        scored.sort(reverse=True)
        return _sanitize([idx for _, idx in scored[:max_count]], n, max_count)

    # [P3] Discard 场景：优先弃死卡（进化卡无前阶在场）或多余能量，保留训练家卡
    if context == _SC_DISCARD:
        scored = []
        for i, opt in enumerate(options):
            cid = _resolve_card_id_from_option(opt, obs_current, my_idx)
            card_data = _CARD_DB.get(cid, {}) if cid >= 0 else {}
            if cid in _TRAINER_IDS:
                priority = 10   # 训练家卡最优先保留
            elif "evolves_from" in card_data:
                priority = 100  # 进化卡（可能为死卡）优先弃
            elif card_data.get("is_energy"):
                priority = 60   # 能量卡次优先弃
            else:
                priority = 30   # 基础宝可梦中优先弃
            scored.append((priority, i))
        scored.sort(reverse=True)
        return _sanitize([idx for _, idx in scored[:max_count]], n, max_count)

    # ToDeck 场景：优先把训练家卡和能量卡放回牌堆
    if context == _SC_TO_DECK:
        scored = []
        for i, opt in enumerate(options):
            cid = _resolve_card_id_from_option(opt, obs_current, my_idx)
            card_data = _CARD_DB.get(cid, {}) if cid >= 0 else {}
            if cid in _TRAINER_IDS:
                priority = 100
            elif card_data.get("is_energy"):
                priority = 80
            elif "evolves_from" in card_data:
                priority = 30
            else:
                priority = 50
            scored.append((priority, i))
        scored.sort(reverse=True)
        return _sanitize([idx for _, idx in scored[:max_count]], n, max_count)

    return _sanitize(list(range(min(max_count, n))), n, max_count)


def _handle_attack(options, max_count, context, obs_current, my_idx):
    """ATTACK(6)：选攻击 — 选伤害最高的（[v22-bugfix] 移除 moves[i] 错位索引）"""
    n = len(options)
    if n == 0:
        return []

    my_active = _get_my_active(obs_current, my_idx)
    my_cid = _get_pokemon_card_id(my_active) if my_active else -1

    scored = []
    for i, opt in enumerate(options):
        attack_id = opt.get("attackId") if isinstance(opt, dict) else None
        dmg = _estimate_attack_damage(my_cid, attack_id)
        scored.append((dmg, i))

    scored.sort(reverse=True)
    return _sanitize([idx for _, idx in scored[:max_count]], n, max_count)


def _handle_yes_no(options, max_count, context, obs_current, my_idx):
    """YES_NO(9)：是/否判断

    [v22.6-fix5] Mulligan(重开) 按场景决策:
      手牌有基础宝可梦 → No (保留手牌)
      手牌没有基础宝可梦 → Yes (重开找基础)
    其余场景 (IsFirst/Activate/CoinHead 等) 一律 Yes。
    """
    n = len(options)
    if n == 0:
        return []

    yes_idx = None
    no_idx = None
    for i, opt in enumerate(options):
        ot = _get_option_type(opt)
        if ot == _OT_YES and yes_idx is None:
            yes_idx = i
        elif ot == _OT_NO and no_idx is None:
            no_idx = i

    if context == _SC_MULLIGAN:
        hand = _get_my_hand(obs_current, my_idx)
        has_basic = False
        for c in hand:
            if not isinstance(c, dict):
                continue
            cid = c.get("id", -1)
            data = _CARD_DB.get(cid, {}) if isinstance(cid, int) else {}
            # 仅在卡库中且非能量、非进化卡的才算基础宝可梦 (训练家不在卡库)
            if not data or data.get("is_energy") is True or "evolves_from" in data:
                continue
            has_basic = True
            break
        if has_basic:
            if no_idx is not None:
                return _sanitize([no_idx], n, max_count)
        else:
            if yes_idx is not None:
                return _sanitize([yes_idx], n, max_count)

    # 先手/特性激活/首个效果/硬币等 → 一律 Yes
    if yes_idx is not None:
        return _sanitize([yes_idx], n, max_count)

    return _sanitize([0], n, max_count)


