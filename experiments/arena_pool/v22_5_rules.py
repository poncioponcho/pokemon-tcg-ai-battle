def _mk_gen_entry(hp, typ, weak, rule, evolves_from, evolves_to, max_dmg):
    """生成卡条目: hp/type/weakness/rule/power/can_attack + 可选的进化链。

    rule: ""=普通, "ex", "mega_ex"; evolves_from>=0 表示有进化前阶 (非基础);
    evolves_to>=0 表示可进化 (用于 _score_play_card 进化奖励)。
    """
    entry = {
        "hp": hp, "type": typ, "weakness": weak, "rule": rule,
        "power": max_dmg, "can_attack": max_dmg > 0,
    }
    if evolves_from >= 0:
        entry["evolves_from"] = evolves_from
    if evolves_to >= 0:
        entry["evolves_to"] = evolves_to
    return entry


