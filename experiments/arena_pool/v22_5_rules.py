def _calculate_ko_damage(base_dmg, my_cid, opp_pokemon):
    """[B1] 计算考虑类型弱点后的实际伤害

    PTCG 弱点规则: 攻击方属性 == 防御方弱点 → 伤害 ×2
    我方卡组属性:
      756: 無 (Colorless)
      344/345: 草 (Grass)
      117: 闘 (Fighting)
    """
    if base_dmg <= 0:
        return 0

    my_data = _CARD_DB.get(my_cid, {})
    my_type = _norm_type_name(my_data.get("type", None))

    opp_weakness = _get_pokemon_weakness(opp_pokemon)

